public class looparray{
    public static void main(){
        int [][]arr={{10,20,30,40},{22,33}};
        for(int row=0;row<arr.length;row++){
            for (int col=0;col<arr[row].length;col++){
                System.out.print(arr[row][col]+" ");
            }System.out.println();
            System.out.println(arr.length);
        }

    
}
}
    

